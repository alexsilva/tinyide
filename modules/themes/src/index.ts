export const builtinThemes: readonly WorkbenchThemeDefinition[] = [
  lightTheme,
  neutralTheme,
  darkTheme,
];

export const builtinThemeProvider: WorkbenchThemeProvider = {
  id: "tinyide.builtin.themes",
  priority: 0,
  themes: () => builtinThemes,
};

export const themeModule: TinyIdeModule = {
  id: "themes",
  version: "0.1.0",
  init(context) {
    context.subscriptions.push(context.extensions.registerWorkbenchThemeProvider(builtinThemeProvider));
  },
};
