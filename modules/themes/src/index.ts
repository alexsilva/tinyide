import type {
  TinyIdeModule,
  WorkbenchThemeDefinition,
  WorkbenchThemeProvider,
  WorkbenchThemeTokens,
} from "@tinyide/plugin-api";

function defineTheme(
  id: string,
  label: string,
  description: string,
  appearance: WorkbenchThemeDefinition["appearance"],
  order: number,
  tokens: WorkbenchThemeTokens,
): WorkbenchThemeDefinition {
  return { id, label, description, appearance, order, tokens };
}

